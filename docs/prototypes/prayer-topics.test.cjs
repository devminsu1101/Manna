const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, 'prayer-topics.html'), 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const scope = {};
for (const name of ['recordPrayer', 'validTopic', 'deleteTopic', 'icon', 'card', 'swipeResult', 'confirmDelete']) {
  const declaration = script.split('\n').find(line => line.startsWith(`function ${name}(`));
  vm.runInNewContext(declaration, scope);
}
const topics = [{ id: 1, active: true, count: 4 }, { id: 2, active: false, count: 3 }, { id: 3, active: true, count: 0 }];
const events = [];
assert.equal(scope.recordPrayer(topics, events), 2);
assert.deepEqual(topics.map(t => t.count), [5, 3, 1]);
assert.deepEqual(Array.from(events[0].topicIds), [1, 3]);
topics[0].active = false;
topics.push({ id: 4, active: true, count: 0 });
assert.deepEqual(Array.from(events[0].topicIds), [1, 3]);
assert.equal(topics[3].count, 0);
assert.equal(scope.recordPrayer([], events), 0);
assert.equal(events.length, 1);
assert.equal(scope.validTopic('기도'.repeat(25), '가'.repeat(1000)), true);
assert.equal(scope.validTopic('가'.repeat(51), ''), false);
assert.equal(scope.validTopic('기도', '가'.repeat(1001)), false);
assert.equal(scope.validTopic('  ', ''), false);
assert.equal(scope.validTopic('기도', ''), true);
assert.equal(scope.swipeResult(20, 350), null);
assert.equal(scope.swipeResult(209, 350), null);
assert.equal(scope.swipeResult(-209, 350), null);
assert.equal(scope.swipeResult(210, 350), 'delete');
assert.equal(scope.swipeResult(-210, 350), 'story');
assert.equal(scope.swipeResult(90, 350), null);
assert.equal(scope.swipeResult(-90, 350), null);
assert.equal(scope.swipeResult(230, 350), 'delete');
assert.equal(scope.swipeResult(150, 250), 'delete');
assert.equal(scope.swipeResult(170, 250), 'delete');
assert.equal(scope.swipeResult(70, 350), null); // Drag back below the threshold before releasing.
const swipeStart = script.indexOf('function setupSwipe(');
vm.runInNewContext(script.slice(swipeStart, script.indexOf('\nfunction renderContent(', swipeStart)), scope);
const listeners = {}, surface = { contains: () => true }, label = {};
let painted, removed;
const row = { clientWidth: 350, style: { setProperty: (_, value) => painted = value }, classList: { toggle() {}, add() {}, remove() {} }, querySelector: selector => selector === '.topic' ? surface : selector === '.swipe-action span' ? label : { dataset: { id: '1' } }, addEventListener: (name, fn) => listeners[name] = fn, setPointerCapture() {} };
scope.setTimeout = fn => fn();
scope.removeWithUndo = id => removed = id;
scope.confirm = () => false;
scope.setupSwipe(row);
const point = (x, y = 0) => ({ isPrimary: true, button: 0, pointerId: 1, clientX: x, clientY: y, target: {} });
listeners.pointerdown(point(0)); listeners.pointermove(point(90)); listeners.pointerup(point(90));
assert.equal(painted, '0px');
assert.equal(removed, undefined);
listeners.pointerdown(point(0)); listeners.pointermove(point(180)); listeners.pointercancel(point(180));
assert.equal(painted, '0px');
assert.equal(removed, undefined);
listeners.pointerdown(point(0)); listeners.pointermove(point(5, 30)); listeners.pointerup(point(5, 30));
assert.equal(painted, '0px');
scope.confirm = () => true;
listeners.pointerdown(point(0)); listeners.pointermove(point(230)); listeners.pointerup(point(230));
assert.equal(removed, 1);
let settle;
scope.setTimeout = fn => { settle = fn; return 1; };
scope.clearTimeout = () => {};
row.isConnected = true;
removed = undefined;
scope.confirm = () => false;
scope.setupSwipe(row);
const wheel = (x, y = 0) => ({ deltaX: x, deltaY: y, deltaMode: 0, preventDefault() {} });
listeners.wheel(wheel(-90)); settle();
assert.equal(painted, '0px');
assert.equal(removed, undefined);
listeners.wheel(wheel(0, 100));
assert.equal(painted, '0px');
scope.confirm = () => true;
listeners.wheel(wheel(-230)); settle();
assert.equal(removed, 1);
scope.topics = [{ id: 1, title: '기록', count: 5, active: true }];
scope.stories = [{ topicId: 1, body: '연결된 나눔' }];
scope.deleteTopic(1);
assert.equal(scope.topics.length, 0);
assert.equal(scope.stories.length, 1);
assert.equal(scope.stories[0].topic.title, '기록');
assert.equal(scope.stories[0].topic.count, 5);
scope.escapeHtml = value => String(value).replaceAll('<', '&lt;');
const ownerCard = scope.card({ id: 2, title: '<제목>', count: 3, active: true, body: '내용' }, true);
assert.match(ownerCard, /type="checkbox"[^>]+checked/);
assert.match(ownerCard, /🙏 3/);
assert.match(ownerCard, /&lt;제목>/);
assert.match(ownerCard, /data-action="delete"/);
assert.match(ownerCard, /data-action="story"/);
assert.doesNotMatch(scope.card({ id: 2, title: '제목', count: 3, active: true }, false), /data-action="(?:delete|edit|toggle)"/);
for (const match of html.matchAll(/src="([^"]+)"/g)) {
  assert.ok(fs.existsSync(path.resolve(__dirname, match[1])), match[1]);
}
const ids = [...html.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]);
assert.equal(ids.length, new Set(ids).size);
for (const match of script.matchAll(/\$\('([^']+)'\)/g)) assert.ok(ids.includes(match[1]), match[1]);
console.log('PASS: script syntax, prayer snapshots, counts, limits, deletion preserves stories, compact controls, assets, DOM references');
